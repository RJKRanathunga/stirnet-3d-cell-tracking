def classify_components(paths: Paths, movie, reviewed: tuple[int, ...], ignored: dict[int, set[int]]) -> pd.DataFrame:
    rows = []
    for t in reviewed:
        base = np.asarray(movie[t]); target = target_frame(paths, movie, t)
        bf, tf = base.reshape(-1), target.reshape(-1)
        active = bf > 0
        b = bf[active].astype(np.int64, copy=False); q = tf[active].astype(np.int64, copy=False)
        stride = max(int(q.max(initial=0)) + 1, 1)
        b2t: dict[int, set[int]] = defaultdict(set); t2b: dict[int, set[int]] = defaultdict(set)
        for encoded in np.unique(b * stride + q).tolist():
            bi, qi = int(encoded // stride), int(encoded % stride)
            b2t[bi].add(qi)
            if qi > 0:
                t2b[qi].add(bi)
        for bi in sorted(int(v) for v in np.unique(base) if int(v) > 0):
            tids = sorted(v for v in b2t.get(bi, set()) if v > 0)
            if set(tids) & ignored.get(t, set()):
                cls = "ignored"
            elif len(tids) == 0:
                cls = "removed"
            elif len(tids) >= 2:
                cls = "merge"
            elif len(t2b.get(tids[0], set())) >= 2:
                cls = "overseg_part"
            else:
                cls = "clean"
            rows.append({"frame": t, "instance_id": bi, "target_class": cls, "target_positive_count": len(tids), "manual_target": paths.manual_frame(t).is_file()})
    result = pd.DataFrame(rows)
    if int((result.target_class == "merge").sum()) == 0:
        raise RuntimeError("No curated merge components found in reviewed frames")
    return result


def dask_movies(paths: Paths):
    import dask.array as da
    source = open_sample(paths.zarr)
    shape = tuple(int(v) for v in source.shape)
    chunks = getattr(source, "chunks", None)
    if chunks is None or len(chunks) != 4:
        chunks = (1, *shape[1:])
    raw = da.from_array(source, chunks=chunks, asarray=False, fancy=False)
    labels_handle = np.load(paths.final_instances, mmap_mode="r", allow_pickle=False)
    labels = da.from_array(labels_handle, chunks=(1, *shape[1:]), asarray=False, fancy=False)
    return source, labels_handle, raw, labels


def build_compact_stabilized_movies(raw_movie, instance_movie, estimate):
    """Lazy stabilization with exactly one delayed full-frame task per timepoint.

    Production build_stabilized_movies() deliberately ends with one full spatial
    frame per Dask chunk because Trackastra normalizes Dask blocks independently.
    However, constructing each padded frame with da.pad() and then
    stack(...).rechunk(full_chunks) can create an enormous intermediate rechunk
    graph on some source-Zarr chunk layouts.

    This Investigation-45-only implementation preserves the same pixel
    semantics and the same final chunk contract, but avoids the pad/stack/rechunk
    graph: each source frame is first represented as one full-frame delayed
    chunk, padded in NumPy when computed, then exposed as one Dask chunk.
    """
    import dask.array as da
    from dask import delayed

    raw_shape = tuple(int(v) for v in raw_movie.shape)
    label_shape = tuple(int(v) for v in instance_movie.shape)
    if raw_shape != label_shape:
        raise ValueError(
            f"Raw/instance movie shape mismatch: {raw_shape} vs {label_shape}"
        )
    if len(raw_shape) != 4:
        raise ValueError(f"Expected (T,Z,Y,X), got {raw_shape}")

    frame_count = int(raw_shape[0])
    original_shape = tuple(int(v) for v in raw_shape[1:])
    canvas_shape = tuple(int(v) for v in estimate.canvas_shape_zyx)
    if estimate.placement_zyx.shape != (frame_count, 3):
        raise ValueError(
            "Motion placement/frame mismatch: "
            f"{estimate.placement_zyx.shape} vs frame_count={frame_count}"
        )

    # One input chunk per complete frame. This is the same normalization
    # requirement as production Trackastra stabilization.
    raw_full = (
        raw_movie.rechunk((1, *original_shape))
        if isinstance(raw_movie, da.Array)
        else da.from_array(
            raw_movie,
            chunks=(1, *original_shape),
            asarray=False,
        )
    )
    labels_full = (
        instance_movie.rechunk((1, *original_shape))
        if isinstance(instance_movie, da.Array)
        else da.from_array(
            instance_movie,
            chunks=(1, *original_shape),
            asarray=False,
        )
    )

    raw_blocks = np.asarray(raw_full.to_delayed(), dtype=object).reshape(frame_count)
    label_blocks = np.asarray(labels_full.to_delayed(), dtype=object).reshape(frame_count)

    def _pad_time_chunk(block_tzyx, placement, canvas):
        block = np.asarray(block_tzyx)
        if block.ndim != 4 or int(block.shape[0]) != 1:
            raise RuntimeError(
                f"Expected one delayed full-frame chunk (1,Z,Y,X), got {block.shape}"
            )
        padded = pad_frame_to_canvas(
            block[0],
            placement_zyx=np.asarray(placement, dtype=np.int64),
            canvas_shape_zyx=tuple(int(v) for v in canvas),
        )
        return padded[np.newaxis, ...]

    raw_frames = []
    label_frames = []
    for t in range(frame_count):
        placement = tuple(int(v) for v in estimate.placement_zyx[t].tolist())

        raw_delayed = delayed(_pad_time_chunk)(
            raw_blocks[t],
            placement,
            canvas_shape,
        )
        label_delayed = delayed(_pad_time_chunk)(
            label_blocks[t],
            placement,
            canvas_shape,
        )

        raw_frames.append(
            da.from_delayed(
                raw_delayed,
                shape=(1, *canvas_shape),
                dtype=raw_full.dtype,
            )
        )
        label_frames.append(
            da.from_delayed(
                label_delayed,
                shape=(1, *canvas_shape),
                dtype=labels_full.dtype,
            )
        )

    stabilized_raw = da.concatenate(raw_frames, axis=0)
    stabilized_labels = da.concatenate(label_frames, axis=0)

    expected_chunks = (
        (1,) * frame_count,
        (canvas_shape[0],),
        (canvas_shape[1],),
        (canvas_shape[2],),
    )
    if stabilized_raw.chunks != expected_chunks:
        raise RuntimeError(
            f"Unexpected stabilized raw chunks: {stabilized_raw.chunks}"
        )
    if stabilized_labels.chunks != expected_chunks:
        raise RuntimeError(
            f"Unexpected stabilized label chunks: {stabilized_labels.chunks}"
        )

    print(
        "[stabilization] compact lazy graph: "
        f"{frame_count} full-frame chunks/movie, canvas={canvas_shape}",
        flush=True,
    )
    return stabilized_raw, stabilized_labels


def hypothesis_contract(paths: Paths, model_name: str, batch_size: int, spacing):
    motion_artifact = (
        paths.bootstrap_motion
        if paths.bootstrap_motion.is_file()
        else paths.output / "derived_bootstrap_motion.csv"
    )
    if not motion_artifact.is_file():
        raise FileNotFoundError(
            "Motion provenance artifact is missing after load_motion(): "
            f"{motion_artifact}"
        )
    return {
        "version": CACHE_VERSION + 3,
        "contract": "compact_lazy_stabilized_trackastra_predict_cuda_fallback_v4",
        "inference_id": paths.inference_id,
        "model_name": model_name,
        "batch_size": int(batch_size),
        "spacing_zyx_um": list(spacing),
        "final_instances": stat_contract(paths.final_instances),
        "motion_artifact": stat_contract(motion_artifact),
        "tracking_summary": stat_contract(paths.trackastra_summary),
        "track_graph": stat_contract(paths.track_graph),
    }



def _cuda_preflight(device: str) -> tuple[bool, dict[str, Any]]:
    """Initialize CUDA/cuBLAS before expensive Trackastra feature extraction.

    CUBLAS_STATUS_NOT_INITIALIZED frequently appears only at the first GEMM.
    Doing a tiny matrix multiply up front lets Investigation 45 fail over to
    CPU before spending ~45 s extracting features on a GPU path that cannot
    actually execute the transformer.
    """
    requested = str(device)
    if not requested.lower().startswith("cuda"):
        return False, {
            "requested_device": requested,
            "cuda_requested": False,
            "cuda_available": None,
        }

    try:
        import torch
    except Exception as exc:
        print(
            f"[cuda preflight] PyTorch unavailable ({exc}); using CPU",
            flush=True,
        )
        return False, {
            "requested_device": requested,
            "cuda_requested": True,
            "cuda_available": False,
            "failure": repr(exc),
        }

    if not torch.cuda.is_available():
        print("[cuda preflight] CUDA is unavailable; using CPU", flush=True)
        return False, {
            "requested_device": requested,
            "cuda_requested": True,
            "cuda_available": False,
        }

    try:
        torch.cuda.empty_cache()
        free_before, total = torch.cuda.mem_get_info()
        # Force lazy CUDA context + cuBLAS initialization now.
        probe = torch.ones((32, 32), device=requested, dtype=torch.float32)
        probe_out = probe @ probe
        torch.cuda.synchronize()
        del probe_out, probe
        torch.cuda.empty_cache()
        free_after, _ = torch.cuda.mem_get_info()
        print(
            "[cuda preflight] PASS "
            f"free={free_after / (1024**3):.2f} GiB / "
            f"{total / (1024**3):.2f} GiB",
            flush=True,
        )
        return True, {
            "requested_device": requested,
            "cuda_requested": True,
            "cuda_available": True,
            "free_before_gib": float(free_before / (1024**3)),
            "free_after_gib": float(free_after / (1024**3)),
            "total_gib": float(total / (1024**3)),
            "cublas_probe": "pass",
        }
    except Exception as exc:
        try:
            torch.cuda.empty_cache()
        except Exception:
            pass
        print(
            "[cuda preflight] FAILED; using CPU instead. "
            f"{type(exc).__name__}: {exc}",
            flush=True,
        )
        return False, {
            "requested_device": requested,
            "cuda_requested": True,
            "cuda_available": True,
            "cublas_probe": "failed",
            "failure": repr(exc),
        }


def _release_trackastra_model(model) -> None:
    if model is not None:
        try:
            del model
        except Exception:
            pass
    gc.collect()
    try:
        import torch
        if torch.cuda.is_available():
            torch.cuda.empty_cache()
    except Exception:
        pass


def _is_cuda_resource_failure(exc: BaseException) -> bool:
    text = str(exc).lower()
    needles = (
        "cublas_status_not_initialized",
        "cublas_status_alloc_failed",
        "cuda out of memory",
        "outofmemoryerror",
        "cuda error",
    )
    return any(token in text for token in needles)


def hypotheses(
    paths: Paths,
    estimate,
    spacing,
    model_name: str,
    device: str,
    batch_size: int,
    rebuild: bool,
):
    nodes_path = paths.cache / "nodes.csv"
    edges_path = paths.cache / "edges.csv"
    manifest_path = paths.cache / "manifest.json"
    runtime_path = paths.cache / "runtime.json"

    contract = hypothesis_contract(paths, model_name, batch_size, spacing)
    if (
        not rebuild
        and nodes_path.is_file()
        and edges_path.is_file()
        and manifest_path.is_file()
        and load_json(manifest_path) == contract
    ):
        print("[hypothesis cache] reuse", flush=True)
        return pd.read_csv(nodes_path), pd.read_csv(edges_path), contract

    requested_device = str(device)
    use_cuda, cuda_info = _cuda_preflight(requested_device)
    active_device = requested_device if use_cuda else "cpu"

    print(
        "[hypothesis cache] running Trackastra neural prediction only "
        f"(requested={requested_device}, active={active_device})",
        flush=True,
    )

    source = labels_handle = raw = labels = model = None
    started = time.perf_counter()
    attempts: list[dict[str, Any]] = []
    try:
        source, labels_handle, raw, labels = dask_movies(paths)
        sr, sl = build_compact_stabilized_movies(raw, labels, estimate)

        def run_once(run_device: str):
            nonlocal model
            config = TrackastraConfig(
                model_name=model_name,
                mode="greedy",
                device=run_device,
                batch_size=batch_size,
                global_motion=GlobalMotionConfig(
                    enabled=True,
                    voxel_size_zyx=tuple(spacing),
                ),
            )
            model = load_trackastra_model(config)

            if str(run_device).lower().startswith("cuda"):
                try:
                    import torch
                    free, total = torch.cuda.mem_get_info()
                    print(
                        "[cuda] Trackastra model loaded: "
                        f"free={free / (1024**3):.2f} GiB / "
                        f"{total / (1024**3):.2f} GiB",
                        flush=True,
                    )
                except Exception:
                    pass

            run_started = time.perf_counter()
            try:
                prediction = model._predict(
                    sr,
                    sl,
                    batch_size=batch_size,
                )
                attempts.append(
                    {
                        "device": str(run_device),
                        "success": True,
                        "seconds": float(time.perf_counter() - run_started),
                    }
                )
                return prediction
            except Exception as exc:
                attempts.append(
                    {
                        "device": str(run_device),
                        "success": False,
                        "seconds": float(time.perf_counter() - run_started),
                        "error_type": type(exc).__name__,
                        "error": str(exc),
                    }
                )
                raise

        try:
            pred = run_once(active_device)
        except RuntimeError as exc:
            if (
                active_device.lower().startswith("cuda")
                and _is_cuda_resource_failure(exc)
            ):
                print(
                    "[cuda] Trackastra association inference failed with a CUDA/"
                    "cuBLAS resource error. Retrying the same neural model on CPU; "
                    "feature extraction will be repeated, but no canonical "
                    "artifacts are modified.",
                    flush=True,
                )
                _release_trackastra_model(model)
                model = None
                active_device = "cpu"
                pred = run_once(active_device)
            else:
                raise

        node_rows = []
        lookup = {}
        for n in pred["nodes"]:
            c = np.asarray(n["coords"], np.float64)
            row = {
                "node_id": int(n["id"]),
                "frame": int(n["time"]),
                "label": int(n["label"]),
                "z_canvas_vox": float(c[0]),
                "y_canvas_vox": float(c[1]),
                "x_canvas_vox": float(c[2]),
            }
            node_rows.append(row)
            lookup[row["node_id"]] = row

        edge_rows = []
        for (src, dst), score in pred["weights"]:
            a, b = lookup[int(src)], lookup[int(dst)]
            edge_rows.append(
                {
                    "source_node_id": int(src),
                    "target_node_id": int(dst),
                    "source_frame": a["frame"],
                    "source_label": a["label"],
                    "target_frame": b["frame"],
                    "target_label": b["label"],
                    "score": float(score),
                    "accepted_solution_edge": False,
                }
            )

        nodes = pd.DataFrame(node_rows)
        edges = pd.DataFrame(edge_rows)
        if (
            not edges.empty
            and np.any(
                edges.target_frame.to_numpy(np.int64)
                - edges.source_frame.to_numpy(np.int64)
                != 1
            )
        ):
            raise RuntimeError(
                "Expected Trackastra hypotheses to be adjacent-frame only"
            )

        paths.cache.mkdir(parents=True, exist_ok=True)
        atomic_csv(nodes_path, nodes)
        atomic_csv(edges_path, edges)
        atomic_json(manifest_path, contract)
        atomic_json(
            runtime_path,
            {
                "requested_device": requested_device,
                "final_device": active_device,
                "cuda_preflight": cuda_info,
                "attempts": attempts,
                "seconds_total": float(time.perf_counter() - started),
            },
        )

        print(
            f"[hypothesis cache] nodes={len(nodes):,} edges={len(edges):,} "
            f"device={active_device} "
            f"time={time.perf_counter() - started:.1f}s",
            flush=True,
        )
        return nodes, edges, contract
    finally:
        _release_trackastra_model(model)


