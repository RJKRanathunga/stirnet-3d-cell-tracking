def make_paths(args: argparse.Namespace) -> Paths:
    record = BioHubCatalog(args.data_root).get(args.sample_id, split=args.split)
    if record.frame_count is None:
        raise RuntimeError("Could not determine BioHub frame count")
    if not record.paths.inference_complete(frame_count=record.frame_count):
        raise RuntimeError(f"Canonical inference incomplete for {record.split}/{record.volume_id}")
    inference_id = record.paths.inference_id()
    if inference_id is None:
        raise RuntimeError("Canonical inference has no inference_id")

    ann_manifest = record.paths.annotation_manifest(args.annotation_set)
    if not ann_manifest.is_file():
        raise FileNotFoundError(ann_manifest)
    ann = load_json(ann_manifest)
    if str(ann.get("base_inference_id", "")) != str(inference_id):
        raise RuntimeError("Annotation set is not bound to the current canonical inference")

    # New canonical tracking writes bootstrap_motion.csv, but older/migrated
    # curation caches can legitimately predate that artifact.  tracking_complete()
    # intentionally does not require bootstrap_motion.csv, so forcing a tracking
    # rebuild here would both waste time and risk changing the temporal evidence
    # bound to the annotations.  Investigation 45 therefore accepts the existing
    # immutable graph and reconstructs the same robust global-motion estimate
    # in-memory when the CSV is absent.
    motion = record.paths.trackastra_root / "bootstrap_motion.csv"
    tracking_summary = load_json(record.paths.trackastra_summary)

    output = resolve(args.output) if args.output else (
        ROOT / "runs" / "stirnet" / "investigations" / SCRIPT_NAME / record.volume_id
    ).resolve()
    return Paths(
        sample=record.volume_id,
        split=record.split,
        annotation_set=args.annotation_set,
        zarr=record.paths.zarr,
        final_instances=record.paths.final_instances,
        track_graph=record.paths.track_graph,
        trackastra_summary=record.paths.trackastra_summary,
        bootstrap_motion=motion,
        instance_annotations=record.paths.instance_annotations(args.annotation_set),
        track_annotations=record.paths.track_annotations(args.annotation_set),
        output=output,
        frame_count=int(record.frame_count),
        inference_id=str(inference_id),
    )


def load_motion(
    paths: Paths,
    shape_zyx: tuple[int, int, int],
    spacing: tuple[float, float, float],
):
    """Load production motion when available, otherwise derive it read-only.

    The fallback is intentionally based on the already-persisted Trackastra
    solution graph.  It uses the exact current production robust estimator:
    adjacent t->t+1 links only, source out-degree=1, target in-degree=1,
    physical-MAD rejection, and cumulative translation.

    This does NOT rewrite canonical tracking.  The derived CSV is stored only
    below the Investigation-45 output directory for provenance/cache reuse.
    """
    spacing_array = np.asarray(spacing, dtype=np.float64)

    if paths.bootstrap_motion.is_file():
        frame = (
            pd.read_csv(paths.bootstrap_motion)
            .sort_values("frame_from")
            .reset_index(drop=True)
        )
        if len(frame) != paths.frame_count - 1:
            raise RuntimeError("bootstrap_motion.csv has wrong transition count")

        pair = frame[["pair_dz", "pair_dy", "pair_dx"]].to_numpy(np.float64)
        cumulative = np.zeros((paths.frame_count, 3), np.float64)
        cumulative[1:] = frame[
            [
                "cumulative_dz_at_to",
                "cumulative_dy_at_to",
                "cumulative_dx_at_to",
            ]
        ].to_numpy(np.float64)

        check = np.zeros_like(cumulative)
        for t in range(1, paths.frame_count):
            check[t] = check[t - 1] + pair[t - 1]
        error_um = np.linalg.norm(
            (check - cumulative) * spacing_array[None],
            axis=1,
        )
        if float(np.max(error_um)) > 1e-4:
            raise RuntimeError(
                "bootstrap motion cumulative displacement is internally inconsistent"
            )

        align = -np.rint(cumulative).astype(np.int64)
        lo, hi = align.min(0), align.max(0)
        placement = align - lo[None]
        canvas = tuple(
            int(v)
            for v in (
                np.asarray(shape_zyx, dtype=np.int64) + (hi - lo)
            ).tolist()
        )
        persisted = frame[
            [
                "placement_z_at_to",
                "placement_y_at_to",
                "placement_x_at_to",
            ]
        ].to_numpy(np.int64)
        if not np.array_equal(persisted, placement[1:]):
            raise RuntimeError(
                "Reconstructed production stabilization differs from "
                "bootstrap_motion.csv"
            )

        estimate = GlobalMotionEstimate(
            pairwise_float_zyx=pair,
            cumulative_float_zyx=cumulative,
            align_int_zyx=align,
            placement_zyx=placement,
            canvas_shape_zyx=canvas,
            pair_counts=frame["pairs_total"].to_numpy(np.int64),
            inlier_counts=frame["pairs_inlier"].to_numpy(np.int64),
            gate_physical=frame["gate_physical"].to_numpy(np.float64),
            median_residual_physical=frame[
                "median_residual_physical"
            ].to_numpy(np.float64),
            p90_residual_physical=frame[
                "p90_residual_physical"
            ].to_numpy(np.float64),
        )
        source = "persisted_production_bootstrap_motion"
        source_artifact = paths.bootstrap_motion
        derived = False

    else:
        print(
            "[global motion] bootstrap_motion.csv is absent in this migrated/"
            "older tracking cache.",
            flush=True,
        )
        print(
            "[global motion] deriving motion read-only from the persisted "
            "Trackastra graph using the current production robust estimator; "
            "canonical tracking will NOT be rebuilt or modified.",
            flush=True,
        )
        with paths.track_graph.open("rb") as handle:
            graph = pickle.load(handle)

        config = GlobalMotionConfig(
            enabled=True,
            voxel_size_zyx=tuple(float(v) for v in spacing),
            minimum_pairs=10,
            mad_scale=4.0,
            minimum_residual_gate_physical=2.0,
        )
        estimate = estimate_global_motion(
            graph,
            frame_count=int(paths.frame_count),
            spatial_shape_zyx=tuple(int(v) for v in shape_zyx),
            config=config,
        )
        del graph

        derived_path = paths.output / "derived_bootstrap_motion.csv"
        atomic_csv(
            derived_path,
            pd.DataFrame(estimate.records()),
        )
        source = "derived_from_persisted_track_graph"
        source_artifact = derived_path
        derived = True

        pair = estimate.pairwise_float_zyx
        cumulative = estimate.cumulative_float_zyx
        canvas = estimate.canvas_shape_zyx

    pair_um = estimate.pairwise_float_zyx * spacing_array[None]
    cumulative_um = estimate.cumulative_float_zyx * spacing_array[None]
    pair_norm = np.linalg.norm(pair_um, axis=1)

    return estimate, {
        "source": source,
        "source_artifact": str(source_artifact.resolve()),
        "derived_fallback": bool(derived),
        "canonical_tracking_modified": False,
        "pairwise_motion_median_um": float(np.median(pair_norm)),
        "pairwise_motion_p90_um": float(np.percentile(pair_norm, 90)),
        "pairwise_motion_max_um": float(np.max(pair_norm)),
        "cumulative_motion_max_um": float(
            np.max(np.linalg.norm(cumulative_um, axis=1))
        ),
        "minimum_pairs_observed": int(np.min(estimate.pair_counts)),
        "minimum_inlier_pairs": int(np.min(estimate.inlier_counts)),
        "canvas_shape_zyx": [int(v) for v in estimate.canvas_shape_zyx],
    }


@dataclass(frozen=True)
class Cell:
    """Canonical persisted spatial detection used by Investigation 45."""

    frame: int
    label: int
    centroid: np.ndarray
    volume_voxels: int
    volume_um3: float


class Cells:
    def __init__(self, movie, spacing, cumulative):
        self.movie = movie
        self.spacing = np.asarray(spacing, np.float64)
        self.cumulative = np.asarray(cumulative, np.float64)
        self.voxel_um3 = float(np.prod(self.spacing))
        self.cache: dict[int, dict[int, Cell]] = {}

    def frame(self, t: int) -> dict[int, Cell]:
        if t in self.cache:
            return self.cache[t]
        p = regionprops_table(np.asarray(self.movie[t]), properties=("label", "centroid", "area"))
        out = {}
        for lab, z, y, x, area in zip(p["label"], p["centroid-0"], p["centroid-1"], p["centroid-2"], p["area"]):
            lab, area = int(lab), int(area)
            out[lab] = Cell(t, lab, np.asarray([z, y, x], np.float64), area, area * self.voxel_um3)
        self.cache[t] = out
        return out

    def get(self, t: int, lab: int) -> Cell | None:
        return self.frame(t).get(lab)

    def raw_um(self, t: int, lab: int) -> np.ndarray:
        return self.frame(t)[lab].centroid * self.spacing

    def stable_um(self, t: int, lab: int) -> np.ndarray:
        return (self.frame(t)[lab].centroid - self.cumulative[t]) * self.spacing


def ignored_ids(paths: Paths, reviewed: set[int]) -> dict[int, set[int]]:
    if not paths.track_state.is_file():
        return {}
    events = load_json(paths.track_state).get("ignored_events", [])
    out: dict[int, set[int]] = defaultdict(set)
    for event in events:
        if not isinstance(event, dict):
            continue
        for key in ("endpoint", "selected_node"):
            node = event.get(key)
            if isinstance(node, (list, tuple)) and len(node) == 2:
                t, lab = int(node[0]), int(node[1])
                if t in reviewed and lab > 0:
                    out[t].add(lab)
    return dict(out)


