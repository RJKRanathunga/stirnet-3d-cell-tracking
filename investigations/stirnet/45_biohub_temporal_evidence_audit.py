def atomic_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    try:
        tmp.write_text(json.dumps(payload, indent=2, sort_keys=True, default=_json), encoding="utf-8")
        os.replace(tmp, path)
    finally:
        tmp.unlink(missing_ok=True)


def atomic_csv(path: Path, frame: pd.DataFrame) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    try:
        frame.to_csv(tmp, index=False)
        os.replace(tmp, path)
    finally:
        tmp.unlink(missing_ok=True)


def _json(value: Any):
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, (np.integer,)):
        return int(value)
    if isinstance(value, (np.floating,)):
        return float(value)
    raise TypeError(type(value).__name__)


def load_json(path: Path) -> dict[str, Any]:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise TypeError(f"Expected JSON object in {path}")
    return value


def parse_frames(text: str) -> tuple[int, ...]:
    values: set[int] = set()
    for raw in str(text).split(","):
        token = raw.strip()
        if not token:
            continue
        if "-" in token:
            a, b = (int(v) for v in token.split("-", 1))
            if b < a:
                raise ValueError(f"Invalid descending range {token!r}")
            values.update(range(a, b + 1))
        else:
            values.add(int(token))
    if not values or min(values) < 0:
        raise ValueError("--reviewed-frames must contain non-negative frame IDs")
    return tuple(sorted(values))


def parse_spacing(text: str) -> tuple[float, float, float]:
    values = tuple(float(v.strip()) for v in text.split(","))
    if len(values) != 3 or any(v <= 0 or not math.isfinite(v) for v in values):
        raise ValueError("--spacing-zyx-um must contain three positive finite Z,Y,X values")
    return values


def stat_contract(path: Path) -> dict[str, Any]:
    st = path.stat()
    return {"path": str(path.resolve()), "size": int(st.st_size), "mtime_ns": int(st.st_mtime_ns)}


def safe_ratio(a: float, b: float) -> float:
    if not math.isfinite(float(a)) or not math.isfinite(float(b)) or b <= 0:
        return math.nan
    return float(a) / float(b)


def abs_log_ratio(a: float, b: float) -> float:
    r = safe_ratio(a, b)
    return abs(math.log(r)) if math.isfinite(r) and r > 0 else math.nan


def eq_diameter(volume_um3: float) -> float:
    return 2.0 * ((3.0 * volume_um3) / (4.0 * math.pi)) ** (1.0 / 3.0)


def finite(values: Iterable[float]) -> np.ndarray:
    arr = np.asarray(list(values), dtype=np.float64)
    return arr[np.isfinite(arr)]


def med(values: Iterable[float]) -> float:
    arr = finite(values)
    return float(np.median(arr)) if arr.size else math.nan


def pct(values: Iterable[float], q: float) -> float:
    arr = finite(values)
    return float(np.percentile(arr, q)) if arr.size else math.nan


