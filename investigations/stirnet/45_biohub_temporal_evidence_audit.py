def accepted_graph(paths: Paths, cells: Cells, relevant: set[int], max_error_um: float) -> Accepted:
    with paths.track_graph.open("rb") as f:
        graph = pickle.load(f)
    by_t: dict[int, list[int]] = defaultdict(list)
    for node, data in graph.nodes(data=True):
        if int(data.get("time", -1)) in relevant:
            by_t[int(data["time"])].append(int(node))
    node_map = {}; errors = []; dropped = 0
    for t in sorted(relevant):
        ids = by_t.get(t, []); canon = cells.frame(t)
        valid_ids, coords = [], []
        for node in ids:
            c = np.asarray(graph.nodes[node].get("coords"), np.float64)
            if c.shape == (3,) and np.all(np.isfinite(c)):
                valid_ids.append(node); coords.append(c)
            else: dropped += 1
        if not valid_ids or not canon: continue
        labels = sorted(canon); cc = np.stack([canon[x].centroid for x in labels]); gc_ = np.stack(coords)
        cost = np.linalg.norm((gc_[:, None] - cc[None]) * cells.spacing[None, None], axis=-1)
        gi, ci = linear_sum_assignment(cost); matched = set()
        for a, b in zip(gi.tolist(), ci.tolist()):
            matched.add(a); err = float(cost[a, b])
            if err <= max_error_um:
                node_map[valid_ids[a]] = (t, labels[b]); errors.append(err)
            else: dropped += 1
        dropped += len(valid_ids) - len(matched)
    if errors and pct(errors, 95) > max_error_um:
        raise RuntimeError(f"Accepted graph mismatch: p95={pct(errors,95):.4f} um")
    edges = set(); parent = {}; outgoing: dict[tuple[int, int], set[tuple[int, int]]] = defaultdict(set)
    for s, d in graph.edges:
        a, b = node_map.get(int(s)), node_map.get(int(d))
        if a is None or b is None or b[0] != a[0] + 1: continue
        e = (a[0], a[1], b[0], b[1]); edges.add(e); outgoing[a].add(b)
        if b in parent and parent[b] != a:
            raise RuntimeError(f"Accepted no-fusion invariant violated at {b}")
        parent[b] = a
    return Accepted(node_map, edges, parent, dict(outgoing), {
        "retained_nodes": len(node_map), "dropped_nodes": dropped,
        "coordinate_error_median_um": med(errors), "coordinate_error_p95_um": pct(errors,95),
        "accepted_adjacent_edges": len(edges),
    })


def validate_hypothesis_nodes(nodes: pd.DataFrame, cells: Cells, estimate, relevant: set[int]) -> dict[str, Any]:
    errors = []
    for r in nodes[nodes.frame.isin(sorted(relevant))].itertuples(index=False):
        cell = cells.get(int(r.frame), int(r.label))
        if cell is None:
            raise RuntimeError(f"Hypothesis node t={r.frame} label={r.label} missing from final_instances")
        got = np.asarray([r.z_canvas_vox, r.y_canvas_vox, r.x_canvas_vox], np.float64)
        expected = cell.centroid + estimate.placement_zyx[int(r.frame)]
        errors.append(float(np.linalg.norm((got - expected) * cells.spacing)))
    if errors and pct(errors, 95) > 0.10:
        raise RuntimeError(f"Hypothesis node/canonical centroid mismatch p95={pct(errors,95):.4f} um")
    return {"checked": len(errors), "median_um": med(errors), "p95_um": pct(errors,95), "max_um": max(errors) if errors else math.nan}


def mark_accepted(edges: pd.DataFrame, accepted: Accepted) -> pd.DataFrame:
    result = edges.copy()
    result["accepted_solution_edge"] = [
        (int(r.source_frame), int(r.source_label), int(r.target_frame), int(r.target_label)) in accepted.edges
        for r in result.itertuples(index=False)
    ]
    return result


def predicted_position(source: tuple[int, int], accepted: Accepted, cells: Cells):
    t, lab = source; p = cells.stable_um(t, lab); parent = accepted.parent.get(source)
    if parent is None or parent[0] != t - 1: return p, False
    return p + (p - cells.stable_um(*parent)), True


def inside_current(position_um, t: int, lab: int, movie, cells: Cells) -> bool:
    source_vox = np.asarray(position_um) / cells.spacing + cells.cumulative[t]
    idx = np.rint(source_vox).astype(np.int64); shape = np.asarray(movie.shape[1:])
    if np.any(idx < 0) or np.any(idx >= shape): return False
    z, y, x = map(int, idx.tolist())
    return int(movie[t, z, y, x]) == lab


