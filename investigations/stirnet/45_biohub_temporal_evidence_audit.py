def auc(y, x):
    y = np.asarray(y,np.int64); x=np.asarray(x,np.float64); m=np.isfinite(x); y,x=y[m],x[m]
    p,n=int((y==1).sum()),int((y==0).sum())
    if p==0 or n==0: return math.nan
    ranks=rankdata(x,method="average"); u=float(ranks[y==1].sum())-p*(p+1)/2
    return u/(p*n)


